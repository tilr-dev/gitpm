"""Group 5 fixtures: a catalog with public Git sources, an author journey and an
offline workspace with a bare origin and a fork."""

import json

from gitpmtest import T, fixture

# Public-looking HTTPS sources resolve to the local author repositories through Git's
# url.<base>.insteadOf (passed in the environment), so a catalog is publishable by
# catalog-update and still installable by gitpm. No network is involved.
PUBLIC = "https://git.example.invalid/"


def public_git_env(root: str = "/fx") -> dict:
    return {"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": f"url.{root}/repos/.insteadOf", "GIT_CONFIG_VALUE_0": PUBLIC}


@fixture(requires=["hello_releases", "numeric"], gitpm=True)
def g5_public_catalog(t: T):
    """/fx/catalog generated by catalog-update from https://git.example.invalid/dan/hello
    (0.1.0, 0.1.1, 0.2.0) and .../dan/num (1.9.0, 1.10.0); empty workspace."""
    (t.root / "sources.txt").write_text(f"{PUBLIC}dan/hello\n{PUBLIC}dan/num\n")
    t.gitpm_ok("catalog-update", env=public_git_env())


@g5_public_catalog.check
def _(t: T):
    for id, versions in [("dan/hello", ["0.1.0", "0.1.1", "0.2.0"]), ("dan/num", ["1.10.0", "1.9.0"])]:
        index = json.loads(t.catalog_index(id).read_text())
        t.eq(index["source"], PUBLIC + id, f"{id} source")
        t.eq(sorted(index["versions"]), versions, f"{id} versions")
        for v in versions:
            release = json.loads(t.catalog_release(id, v).read_text())
            t.eq(release["source"], PUBLIC + id, f"{id}@{v} source")
            t.ok(release.get("files"), f"{id}@{v} has file hashes")
    t.ok(not t.ws.exists(), "workspace untouched")


@fixture(gitpm=True)
def g5_journey(t: T):
    """Author journey up to the first catalog: `init dan/journey --into authors/journey`
    (dan/journey 0.1.0), dist edited, `commit 0.1.1`, sources.txt lists the folder,
    catalog-update generated /fx/catalog."""
    t.gitpm_ok("init", "dan/journey", "--into", t.root / "authors/journey")
    repo = t.root / "authors/journey"
    t.write(repo, {"dist/index.js": "export const greeting = 'journey 0.1.1';\n"})
    t.gitpm_ok("commit", repo, "0.1.1")
    (t.root / "sources.txt").write_text("authors/journey\n")
    t.gitpm_ok("catalog-update")


@g5_journey.check
def _(t: T):
    repo = t.root / "authors/journey"
    t.eq(sorted(t.git(repo, "tag", "--list").split()), ["dan/journey@0.1.0", "dan/journey@0.1.1"], "tags")
    t.eq(t.git(repo, "status", "--porcelain"), "", "clean worktree")
    index = json.loads(t.catalog_index("dan/journey").read_text())
    t.eq(sorted(index["versions"]), ["0.1.0", "0.1.1"], "catalog versions")
    t.ok(not t.ws.exists(), "workspace untouched")


@fixture(requires=["hello"], gitpm=True)
def g5_offline(t: T):
    """dan/hello installed from the bare origin /fx/origin/hello.git at 0.1.0 and updated
    to 0.1.1 (previous 0.1.0); fork mine/hello (author folder /fx/authors/mine-hello,
    release mine/hello@0.1.2) installed beside it from its author folder."""
    bare = t.root / "origin/hello.git"
    t.run("git", "clone", "-q", "--bare", t.repo("dan/hello"), bare, check=True)
    t.gitpm_ok("install", bare, "--ref", "dan/hello@0.1.0")
    t.release("dan/hello", "0.1.1")
    t.git("dan/hello", "push", "-q", str(bare), "main", "--tags")
    t.gitpm_ok("update", "dan/hello")
    fork = t.root / "authors/mine-hello"
    t.gitpm_ok("fork", "dan/hello", "--ns", "mine", "--into", fork)
    t.write(fork, {"dist/index.js": "export const greeting = 'mine fork';\n"})
    t.gitpm_ok("commit", fork, "0.1.2")
    t.gitpm_ok("install", fork, "--ref", "mine/hello@0.1.2")


@g5_offline.check
def _(t: T):
    p = t.plugin("dan/hello")
    t.eq(p["current"]["version"], "0.1.1", "dan/hello current")
    t.eq(p["previous"]["version"], "0.1.0", "dan/hello previous")
    t.eq(p["source"], str(t.root / "origin/hello.git"), "dan/hello source is the bare origin")
    f = t.plugin("mine/hello")
    t.eq(f["current"]["version"], "0.1.2", "fork current")
    t.eq(f["forkOf"]["id"], "dan/hello", "fork provenance")
    t.has((t.dist("mine/hello") / "index.js").read_text(), "mine fork")
    t.has((t.dist("dan/hello") / "index.js").read_text(), "dan/hello 0.1.1")
