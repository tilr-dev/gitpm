"""Group 5 fixtures: a catalog with public Git sources, an author journey and an
offline workspace with a bare origin and a fork."""

import json

from gitpmtest import T, fixture

# Public-looking HTTPS sources resolve to the local author repositories through Git's
# url.<base>.insteadOf (passed in the environment), so a catalog is publishable by
# catalog-update and still installable by gitpm. No network is involved.
PUBLIC = "https://git.example.invalid/"


def public_git_env(root: str = "/fx") -> dict:
    return {"GIT_CONFIG_COUNT": "1", "GIT_CONFIG_KEY_0": f"url.{root}/repos/.insteadOf", "GIT_CONFIG_VALUE_0": PUBLIC}


@fixture(requires=["hello_releases", "numeric"], gitpm=True)
def g5_public_catalog(t: T):
    """/fx/catalog generated by catalog-update from https://git.example.invalid/3dce1568-569c-5b53-9321-37185e751947
    (0.1.0, 0.1.1, 0.2.0) and .../2190eee8-4be5-5a91-81d2-6ca95c1e61d0 (1.9.0, 1.10.0); empty workspace."""
    (t.root / "sources.txt").write_text(f"{PUBLIC}3dce1568-569c-5b53-9321-37185e751947\n{PUBLIC}2190eee8-4be5-5a91-81d2-6ca95c1e61d0\n")
    t.gitpm_ok("catalog-update", env=public_git_env())


@g5_public_catalog.check
def _(t: T):
    for id, versions in [("3dce1568-569c-5b53-9321-37185e751947", ["0.1.0", "0.1.1", "0.2.0"]), ("2190eee8-4be5-5a91-81d2-6ca95c1e61d0", ["1.10.0", "1.9.0"])]:
        index = json.loads(t.catalog_index(id).read_text())
        t.eq(index["source"], PUBLIC + id, f"{id} source")
        t.eq(sorted(index["versions"]), versions, f"{id} versions")
        for v in versions:
            release = json.loads(t.catalog_release(id, v).read_text())
            t.eq(release["source"], PUBLIC + id, f"{id}@{v} source")
            t.ok(release.get("files"), f"{id}@{v} has file hashes")
    t.ok(not t.ws.exists(), "workspace untouched")


@fixture(gitpm=True)
def g5_journey(t: T):
    """Authored journey fixture up to the first catalog: authors/journey
    (0c318dfa-7376-5e00-8edd-81474abe756a 0.1.0), dist edited, `commit 0.1.1`, sources.txt lists the folder,
    catalog-update generated /fx/catalog."""
    repo = t.root / "authors/journey"
    repo.mkdir(parents=True)
    t.git(repo, "init", "-q", "-b", "main")
    t.commit(repo, "Initial author fixture", {
        "plugin.json": json.dumps({"id": "0c318dfa-7376-5e00-8edd-81474abe756a", "name": "journey", "version": "0.1.0"}) + "\n",
        "dist/index.js": "export const greeting = 'journey 0.1.0';\n",
    })
    t.git(repo, "tag", "v0.1.0")
    t.write(repo, {"dist/index.js": "export const greeting = 'journey 0.1.1';\n"})
    t.gitpm_ok("commit", repo, "0.1.1")
    (t.root / "sources.txt").write_text("authors/journey\n")
    t.gitpm_ok("catalog-update")


@g5_journey.check
def _(t: T):
    repo = t.root / "authors/journey"
    t.eq(sorted(t.git(repo, "tag", "--list").split()), ["v0.1.0", "v0.1.1"], "tags")
    t.eq(t.git(repo, "status", "--porcelain"), "", "clean worktree")
    index = json.loads(t.catalog_index("0c318dfa-7376-5e00-8edd-81474abe756a").read_text())
    t.eq(sorted(index["versions"]), ["0.1.0", "0.1.1"], "catalog versions")
    t.ok(not t.ws.exists(), "workspace untouched")


@fixture(requires=["hello"], gitpm=True)
def g5_offline(t: T):
    """3dce1568-569c-5b53-9321-37185e751947 installed from the bare origin /fx/origin/hello.git at 0.1.0 and updated
    to 0.1.1 (previous 0.1.0); fork b70acb45-e742-5e38-9b58-984cc80542a4 (author folder /fx/authors/mine-hello,
    release b70acb45-e742-5e38-9b58-984cc80542a4@0.1.2) installed beside it from its author folder."""
    bare = t.root / "origin/hello.git"
    t.run("git", "clone", "-q", "--bare", t.repo("3dce1568-569c-5b53-9321-37185e751947"), bare, check=True)
    t.gitpm_ok("install", bare)
    t.release("3dce1568-569c-5b53-9321-37185e751947", "0.1.1")
    t.git("3dce1568-569c-5b53-9321-37185e751947", "push", "-q", str(bare), "main", "--tags")
    t.gitpm_ok("update", "3dce1568-569c-5b53-9321-37185e751947")
    fork = t.root / "authors/mine-hello"
    fork.mkdir(parents=True)
    t.git(fork, "init", "-q", "-b", "fork")
    original = t.package("3dce1568-569c-5b53-9321-37185e751947")
    base = {"id": "3dce1568-569c-5b53-9321-37185e751947", "version": "0.1.1"}
    t.commit(fork, "Initial independent fork fixture", {
        "plugin.json": json.dumps({"id": "b70acb45-e742-5e38-9b58-984cc80542a4", "name": "hello", "version": "0.1.1", "replaces": base,
                                  "forkOf": {**base, "commit": original["current"]["commit"], "source": str(bare)}}) + "\n",
        "dist/index.js": "export const greeting = 'mine fork base';\n",
    })
    t.git(fork, "remote", "add", "upstream", str(bare))
    t.write(fork, {"dist/index.js": "export const greeting = 'mine fork';\n"})
    t.gitpm_ok("commit", fork, "0.1.2")
    t.gitpm_ok("install", fork)


@g5_offline.check
def _(t: T):
    p = t.package("3dce1568-569c-5b53-9321-37185e751947")
    t.eq(p["current"]["version"], "0.1.1", "3dce1568-569c-5b53-9321-37185e751947 current")
    t.eq(p["previous"]["version"], "0.1.0", "3dce1568-569c-5b53-9321-37185e751947 previous")
    t.eq(p["source"], str(t.root / "origin/hello.git"), "3dce1568-569c-5b53-9321-37185e751947 source is the bare origin")
    f = t.package("b70acb45-e742-5e38-9b58-984cc80542a4")
    t.eq(f["current"]["version"], "0.1.2", "fork current")
    t.eq(f["forkOf"]["id"], "3dce1568-569c-5b53-9321-37185e751947", "fork provenance")
    t.has((t.dist("b70acb45-e742-5e38-9b58-984cc80542a4") / "index.js").read_text(), "mine fork")
    t.has((t.dist("3dce1568-569c-5b53-9321-37185e751947") / "index.js").read_text(), "3dce1568-569c-5b53-9321-37185e751947 0.1.1")
